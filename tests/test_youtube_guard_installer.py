    def test_extension_zip_is_deterministic_and_has_root_manifest(self):
        with tempfile.TemporaryDirectory() as td:
            exports = []
            for target_os in ("linux", "windows", "macos", "chromeos"):
                target = Path(td) / target_os
                core.export_bundle(settings(target_os=target_os), target)
                archive_bytes = (target / "extension.zip").read_bytes()
                exports.append(archive_bytes)
                with zipfile.ZipFile(io.BytesIO(archive_bytes)) as archive:
                    self.assertEqual(set(archive.namelist()),
                                     {"manifest.json", "rules.json", "config.json"})
                    self.assertEqual(len(archive.namelist()), 3)
                    for name in archive.namelist():
                        self.assertEqual(archive.read(name),
                                         (target / "extension" / name).read_bytes())
                    manifest = json.loads(archive.read("manifest.json"))
                    self.assertEqual(manifest["manifest_version"], 3)
                    self.assertEqual(manifest["declarative_net_request"]["rule_resources"][0]["path"],
                                     "rules.json")
            self.assertTrue(all(archive == exports[0] for archive in exports))

